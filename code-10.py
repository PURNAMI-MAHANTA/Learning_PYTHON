# Some Escape sequence characters \n-->new line, \t-->tab space, \r-->Carriage return, \v-->vertical tab, \"-->Double Quote, \'-->Single Quote
anime = "I love to watch anime\nCurrently I am watching \"One Piece\""
print(anime)

skill = "I have started to learn a new skill\t\"PYTHON\""
print(skill)

welcome = "Welcome\nIt\'s my github profile"
print(welcome)

new = "Learning\vnew\vskills"
print(new)

code = "Love\rcoding"
print(code)
